def build():
    rows, counters = [], Counter()
    for category, product, expected, difficulty, rationale, disputed in CASES:
        counters[category] += 1
        rows.append({
            "id": f"{PREFIX[category]}{counters[category]:02d}",
            "diet": DIETS[category],
            "product": product,
            "expected": expected,
            "category": category,
            "difficulty": difficulty,
            "rationale": rationale,
            "disputed": disputed,
        })
    return rows


if __name__ == "__main__":
    rows = build()
    out = Path(__file__).with_name("cases.jsonl")
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(len(rows), "cases ->", out.name)
    print("expected:", dict(Counter(r["expected"] for r in rows)))
    print("difficulty:", dict(Counter(r["difficulty"] for r in rows)))
    print("categories:", len({r["category"] for r in rows}), "disputed:", sum(r["disputed"] for r in rows))
